/** 방 크기 36×21: 위쪽 2줄 벽, 안쪽 34×18, 아래 1줄 벽. 템플릿(28×14)은 가운데에 놓고 둘레는 바닥 */
export const DOOR_SLOTS = [10, 17, 24]; // 위쪽 벽 문 위치 (2칸 문의 왼쪽 칸)
export const BRAZIER_COLS = [4, 14, 21, 31];
export const ENTRANCE_COL = 17;
const W = 36;
const INNER_W = 34;
const INNER_H = 18;
const PAD_X = 3;
const PAD_TOP = 2;

/** 안쪽 템플릿을 36×21 전체 레이아웃으로 감싼다 */
export function wrapTemplate(t: RoomTemplate, opts: { braziers?: boolean } = {}): string[] {
  const top = '#'.repeat(W);
  const face = Array.from({ length: W }, (_, c) => (opts.braziers !== false && BRAZIER_COLS.includes(c) ? 'b' : '#')).join('');
  const blank = '.'.repeat(INNER_W);
  const rows: string[] = [];
  for (let r = 0; r < INNER_H; r++) {
    const src = t.rows[r - PAD_TOP];
    const inner = src === undefined ? blank : '.'.repeat(PAD_X) + src.padEnd(28, '.').slice(0, 28) + '.'.repeat(INNER_W - PAD_X - 28);
    rows.push('#' + inner + '#');
  }
  return [top, face, ...rows, '#'.repeat(W)];
}

/** 템플릿에서 특수 표식 위치 찾기 (타일 좌표) */
export function findMarkers(layout: string[], ch: string): { c: number; r: number }[] {
  const out: { c: number; r: number }[] = [];
  layout.forEach((row, r) => {
    for (let c = 0; c < row.length; c++) if (row[c] === ch) out.push({ c, r });
  });
  return out;
}

/**
 * 보라 먼지 평원 기반 맵: 움직이는 곳은 78×46칸 (처음 65×38칸 = 실험실 36×21의 1.8배였다가 2026-11-10 사용자 요청으로 1.2배 더). 벽은 없고,
 * 바닥이 그 바깥까지 이어져 보이지만 바깥으로는 못 나간다 (보이지 않는 경계).
 * 한가운데 a = 산소탑 (2×2칸 왼쪽 위, 탑 바닥 가운데가 맵 한가운데), 그 조금 아래 p = 플레이어 시작.
 * 광물·수소 구멍은 dustZone.ts가 랜덤으로 놓음.
 */
// 바깥 여백 17·10칸 = 화면 반 + 카메라가 마우스 쪽으로 앞서 보는 거리 → 가장자리에 서도 화면 끝까지 땅이 그려짐
const DUST_PLAY = { c: 17, r: 10, w: 78, h: 46 };
export const DUST_TEMPLATE: RoomTemplate = { id: 'dust', name: '보라 먼지 평원', play: DUST_PLAY, rows: makeDustRows() };

function makeDustRows(): string[] {
  const { c, r, w, h } = DUST_PLAY;
  const W = w + 2 * c, H = h + 2 * r;
  const cx = W >> 1, cy = H >> 1;
  const rows = Array.from({ length: H }, () => '.'.repeat(W));
  const put = (x: number, y: number, ch: string) => (rows[y] = rows[y].slice(0, x) + ch + rows[y].slice(x + 1));
  put(cx - 1, cy - 2, 'a');
  put(cx, cy + 2, 'p');
  return rows;
}

